export function getBookById(id) {
  if (!id) return BOOKS[0];
  const normalized = String(id).toLowerCase();
  return (
    BOOKS.find((b) => b.id === normalized || b.gutenbergId === normalized) ||
    BOOKS.find((b) => b.id.includes(normalized)) ||
    BOOKS[4] // default to Crime and Punishment (#2554)
  );
}
